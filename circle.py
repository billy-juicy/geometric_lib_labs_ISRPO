import math


def area(r):
    """
    Вычисляет площадь круга по его радиусу.

    :param r: радиус круга (число > 0)
    :return: плозадь круга (float)

    Пример вызова функции:
        area(5)
        78.53981633974483
    """

    return math.pi * r * r


def perimeter(r):
    """
    Вычисляет длину окружности (периметр круга) по его радиусу.

    :param r: радиус круга (число > 0)
    :return: длина окружности (float)

    Пример вызова:
        perimeter(5)
        31.41592653589793
    """

    return 2 * math.pi * r
