def area(a):
    """
    Вычисляет площадь квадрата по длине его стороны.

    :param a: длина стороны квадрата (число > 0)
    :return: площадь квадрата (int/float)

    Пример вызова:
        area(4)
        16
    """

    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата по длине его стороны.

    :param a: длина стороны квадрата (число > 0)
    :return: периметр квадрата (int/float)

    Пример вызова:
        perimeter(4)
        16
    """

    return 4 * a
