def area(a):
    """
    Вычисляет площадь квадрата по длине его стороны.

    Параметры:
    a (int): длина стороны квадрата (число > 0)
    return (int): площадь квадрата

    Пример вызова:
        area(4)
        16
    """

    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата по длине его стороны.

    Параметры:
    a (int): длина стороны квадрата (число > 0)
    return (int): периметр квадрата

    Пример вызова:
        perimeter(4)
        16
    """

    return 4 * a
